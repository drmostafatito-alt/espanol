def build_thematic_callcenter(existing_norms: set[str]):
    entries = []
    seen = set()
    rank = 1

    for row in CALLCENTER_ITEMS:
        kind = row[0]
        headword = row[1]
        param = row[2]
        level = row[3]
        msa = row[4]
        eg = row[5]
        domain = row[6]

        norm = norm_vocab(headword)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        if kind == "noun":
            gender = param if param in ("m", "f", "mf") else "m"
            art = "El" if gender == "m" else "La"
            ex_es = f"{art} {headword} es un término fundamental en la atención al cliente."
            ex_ar = f"الـ{msa} مصطلح أساسي في خدمة العملاء."
            entry = make_noun(headword, gender, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        elif kind == "verb":
            paradigm = param or "ar"
            ex_es = f"Los teleoperadores suelen {headword} para gestionar la llamada."
            ex_ar = f"يعتاد موظفو الخدمة أن {msa} لإدارة المكالمة."
            entry = make_verb(headword, paradigm, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        else:
            ex_es = f"Se aplica {headword} durante el servicio telefónico."
            ex_ar = f"يُطبق {msa} أثناء الخدمة الهاتفية."
            entry = make_adv(headword, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)

        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-topic-callcenter.json",
        bundle_slug="cv-topic-callcenter",
        title_ar="معجم خدمة العملاء والدعم الفني ومراكز الاتصال",
        entries=entries
    )
    return len(entries), seen

if __name__ == "__main__":
    count, _ = build_thematic_callcenter(get_existing_norms())
    print(f"Generated {count} entries in vocab-cv-topic-callcenter.json")
