def main():
    print("Building nouns comprehensive datasets...")
    existing = get_existing_norms()
    entries = []
    seen = set()

    rank = 1
    for row in DAILY_NOUNS:
        headword = row[0]
        norm = norm_vocab(headword)
        if norm in existing or norm in seen:
            continue
        seen.add(norm)

        gender = row[1]
        level = row[2]
        msa = row[3]
        eg = row[4]
        domain = row[5]

        # صياغة جملة إسبانية طبيعية ومضمونة لاحتواء الكلمة
        if gender == "m":
            art = "El"
            adj_es = "esencial"
        elif gender == "f":
            art = "La"
            adj_es = "esencial"
        else:
            art = "El"
            adj_es = "esencial"

        ex_es = f"{art} {headword} suele ser {adj_es} en la vida diaria."
        ex_ar = f"الـ{msa} أساسي في الحياة اليومية عادة."

        entry = make_noun(headword, gender, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-nouns-daily.json",
        bundle_slug="cv-nouns-daily",
        title_ar="أسماء الحياة اليومية والمنزل والطعام والأزياء",
        entries=entries
    )
    print(f"Total nouns generated in cv-nouns-daily: {len(entries)}")

if __name__ == "__main__":
    main()
