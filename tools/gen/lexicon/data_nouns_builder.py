def build_daily_bundle(existing_norms):
    entries = []
    seen = set()
    rank = 1
    
    all_data = list(DAILY_LIST) + list(SYSTEMATIC_DAILY)
    for row in all_data:
        headword = row[0]
        norm = norm_vocab(headword)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        gender = row[1]
        level = row[2]
        msa = row[3]
        eg = row[4]
        domain = row[5]

        art = "El" if gender == "m" else "La"
        adj = "útil" if gender == "m" else "útil"
        ex_es = f"{art} {headword} es muy {adj} en el día a día."
        ex_ar = f"الـ{msa} مفيد جدًا في المعيشة اليومية."

        entry = make_noun(headword, gender, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-nouns-daily.json",
        bundle_slug="cv-nouns-daily",
        title_ar="أسماء الحياة اليومية والمنزل والطعام والأدوات",
        entries=entries
    )
    return len(entries), seen

if __name__ == "__main__":
    count, _ = build_daily_bundle(get_existing_norms())
    print(f"Generated {count} daily nouns.")
