def build_thematic_food(existing_norms: set[str]):
    entries = []
    seen = set()
    rank = 1

    for row in FOOD_ITEMS:
        kind = row[0]
        headword = row[1]
        param = row[2]
        level = row[3]
        msa = row[4]
        eg = row[5]
        domain = row[6]

        norm = norm_vocab(headword)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        if kind == "noun":
            gender = param if param in ("m", "f", "mf") else "m"
            art = "El" if gender == "m" else "La"
            ex_es = f"{art} {headword} es un ingrediente muy popular en la cocina."
            ex_ar = f"الـ{msa} مكون شعبي جداً في المطبخ."
            entry = make_noun(headword, gender, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        elif kind == "verb":
            paradigm = param or "ar"
            ex_es = f"Se suele {headword} para preparar deliciosos platos tradicionales."
            ex_ar = f"يُعتاد أن {msa} لإعداد أطباق تقليدية لذيذة."
            entry = make_verb(headword, paradigm, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        else:
            ex_es = f"Consumimos {headword} de manera habitual en las comidas."
            ex_ar = f"نستهلك {msa} بصورة معتادة في الوجبات."
            entry = make_adv(headword, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)

        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-topic-food.json",
        bundle_slug="cv-topic-food",
        title_ar="معجم المأكولات والمطاعم والطهي والمشروبات الإسبانية",
        entries=entries
    )
    return len(entries), seen

