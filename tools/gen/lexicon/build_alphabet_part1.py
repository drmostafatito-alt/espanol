def build_alphabet_part1(existing_norms: set[str]):
    entries = []
    seen = set()
    rank = 1

    for row in ITEMS_A_F:
        kind = row[0]
        headword = row[1]
        param = row[2]
        level = row[3]
        msa = row[4]
        eg = row[5]
        domain = row[6]

        norm = norm_vocab(headword)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        if kind == "noun":
            gender = param if param in ("m", "f", "mf") else "m"
            art = "El" if gender == "m" else "La"
            ex_es = f"{art} {headword} es muy conocido en este ámbito."
            ex_ar = f"الـ{msa} معروف جداً في هذا المجال."
            entry = make_noun(headword, gender, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        elif kind == "verb":
            paradigm = param or "ar"
            ex_es = f"Solemos {headword} con bastante frecuencia."
            ex_ar = f"نعتاد أن {msa} بتكرار كاف."
            entry = make_verb(headword, paradigm, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        elif kind == "adj":
            ex_es = f"Este aspecto resulta muy {headword} para todos."
            ex_ar = f"هذا الجانب {msa} جداً للجميع."
            entry = make_adj(headword, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        else:
            ex_es = f"Usamos {headword} de manera habitual."
            ex_ar = f"نستخدم {msa} بشكل معتاد."
            entry = make_adv(headword, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)

        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-alphabet-b-f.json",
        bundle_slug="cv-alphabet-b-f",
        title_ar="المعجم الشامل للحروف B و D و F: أسماء وأفعال وصفات",
        entries=entries
    )
    return len(entries), seen

