/* ============================================================================
   أدوات مولّد حتمي — **ليست لأي غرض أمني** (إصلاح DEFECT-1)
   ----------------------------------------------------------------------------
   كانت هنا دالة خلط حتمية ببذرة نصية تُستخدم لإخفاء مواضع الإجابات، وتبيّن
   أنها قابلة لإعادة الحساب من بيانات يعرفها العميل (attemptId/userId …).
   حُذفت من كل مسارات الحماية لصالح `shuffleSecure` في ‏./random.ts.

   ما بقي هنا: مولّد mulberry32 مع بذرة FNV-1a — يُستخدم حصرًا كمصدر
   عشوائية **قابل للحقن في الاختبارات** (setRandomSourceForTests) حتى تكون
   اختبارات الهجوم والتوزيع حتمية وقابلة للتكرار. لا تستخدمه لإخفاء أي
   معلومة عن العميل.
   ========================================================================== */

/** FNV-1a 32-bit: بذرة مستقرة من سلسلة (للاختبارات الحتمية) */
export function seedFromString(seed: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < seed.length; i++) {
    hash ^= seed.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

/** mulberry32: مولّد صغير حتمي — للاختبارات فقط، أبدًا لأي غرض تشفيري/حماية */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
