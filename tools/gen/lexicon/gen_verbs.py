def main():
    print("Building verbs expanded dataset...")
    existing = get_existing_norms()
    entries = []
    seen = set()

    all_specs = list(RAW_VERBS)
    
    # تحويل Extended verbs specs إلى مدخلات كاملة
    for item in EXTENDED_VERBS_SPECS:
        lemma, paradigm, level, msa, eg, domain = item
        norm = norm_vocab(lemma)
        if norm in existing or norm in seen:
            continue
        ex_es = f"Suelo {lemma} todos los días con atención."
        ex_ar = f"أعتاد أن {msa} كل يوم باهتمام."
        all_specs.append((lemma, paradigm, level, msa, eg, ex_es, ex_ar, domain, f"فعل من مستوى {level}.", ""))

    rank = 1
    for row in all_specs:
        lemma = row[0]
        norm = norm_vocab(lemma)
        if norm in existing or norm in seen:
            continue
        seen.add(norm)
        
        paradigm = row[1] if len(row) > 1 else "ar"
        level = row[2] if len(row) > 2 else "A2"
        msa = row[3] if len(row) > 3 else "يفعل"
        eg = row[4] if len(row) > 4 else msa
        ex_es = row[5] if len(row) > 5 else f"Debes {lemma} bien."
        ex_ar = row[6] if len(row) > 6 else f"عليك أن {msa} جيدًا."
        domain = row[7] if len(row) > 7 else "daily"
        usage = row[8] if len(row) > 8 else ""
        err = row[9] if len(row) > 9 else ""

        entry = make_verb(lemma, paradigm, level, msa, eg, ex_es, ex_ar, domain, usage, err, rank)
        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-verbs-expanded.json",
        bundle_slug="cv-verbs-expanded",
        title_ar="الأفعال الإسبانية الموسعة (A1..C1)",
        entries=entries
    )
    print(f"Total new verbs generated: {len(entries)}")

if __name__ == "__main__":
    main()
