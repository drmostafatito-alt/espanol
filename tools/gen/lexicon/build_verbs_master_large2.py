def build_verbs_expansion_2(existing_norms: set[str]):
    entries = []
    seen = set()
    rank = 1

    for row in VERBS_EXPANSION_2:
        lemma = row[0]
        norm = norm_vocab(lemma)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        paradigm = row[1]
        level = row[2]
        msa = row[3]
        eg = row[4]
        domain = row[5]

        ex_es = f"Solemos {lemma} de manera habitual en nuestro trabajo diario."
        ex_ar = f"نعتاد أن {msa} بصورة اعتيادية في عملنا اليومي."

        entry = make_verb(lemma, paradigm, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-verbs-master-large2.json",
        bundle_slug="cv-verbs-master-large2",
        title_ar="معجم الأفعال الإسبانية الكبرى الشاملة والمتنوعة",
        entries=entries
    )
    return len(entries), seen

