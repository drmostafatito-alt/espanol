def build_alphabet_part5(existing_norms: set[str]):
    entries = []
    seen = set()
    rank = 1

    for row in ITEMS_U_Z:
        kind = row[0]
        headword = row[1]
        param = row[2]
        level = row[3]
        msa = row[4]
        eg = row[5]
        domain = row[6]

        norm = norm_vocab(headword)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        if kind == "noun":
            gender = param if param in ("m", "f", "mf") else "m"
            art = "El" if gender == "m" else "La"
            ex_es = f"{art} {headword} es un concepto clave en este contexto."
            ex_ar = f"الـ{msa} مفهوم أساسي في هذا السياق."
            entry = make_noun(headword, gender, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        elif kind == "verb":
            paradigm = param or "ar"
            ex_es = f"Solemos {headword} con bastante frecuencia."
            ex_ar = f"نعتاد أن {msa} بتكرار كاف."
            entry = make_verb(headword, paradigm, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        elif kind == "adj":
            ex_es = f"Este elemento es muy {headword} en la vida diaria."
            ex_ar = f"هذا العنصر {msa} جداً في الحياة اليومية."
            entry = make_adj(headword, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        else:
            ex_es = f"Trabajamos {headword} para lograr el éxito en cada tarea."
            ex_ar = f"نعمل {msa} لتحقيق النجاح في كل مهمة."
            entry = make_adv(headword, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)

        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-alphabet-u-z.json",
        bundle_slug="cv-alphabet-u-z",
        title_ar="معجم الحروف الإسبانية U حتى Z وظروف الحال",
        entries=entries
    )
    return len(entries), seen

if __name__ == "__main__":
    count, _ = build_alphabet_part5(get_existing_norms())
    print(f"Generated {count} entries in vocab-cv-alphabet-u-z.json")
