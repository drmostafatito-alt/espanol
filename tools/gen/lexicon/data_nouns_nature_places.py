def build_places_nature_bundle(existing_norms):
    entries = []
    seen = set()
    rank = 1

    for row in NATURE_PLACES_LIST:
        headword = row[0]
        norm = norm_vocab(headword)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        gender = row[1]
        level = row[2]
        msa = row[3]
        eg = row[4]
        domain = row[5]

        art = "El" if gender == "m" else "La"
        adj = "bello" if gender == "m" else "bella"
        ex_es = f"{art} {headword} forma parte de la naturaleza de la zona."
        ex_ar = f"الـ{msa} يشكل جزءًا من طبيعة المنطقة."

        entry = make_noun(headword, gender, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-nouns-places-nature.json",
        bundle_slug="cv-nouns-places-nature",
        title_ar="أسماء الأماكن والمدينة والطبيعة والحيوانات والجغرافيا",
        entries=entries
    )
    return len(entries), seen

