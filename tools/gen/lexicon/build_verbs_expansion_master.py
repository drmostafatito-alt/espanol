def build_verbs_expansion(existing_norms: set[str]):
    entries = []
    seen = set()
    rank = 1

    for row in VERBS_MEGA_LIST:
        lemma = row[0]
        norm = norm_vocab(lemma)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        paradigm = row[1]
        level = row[2]
        msa = row[3]
        eg = row[4]
        domain = row[5]

        ex_es = f"Solemos {lemma} con bastante frecuencia en estas situaciones."
        ex_ar = f"نعتاد أن {msa} بتكرار كاف في هذه المواقف."

        entry = make_verb(lemma, paradigm, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-verbs-expanded-master.json",
        bundle_slug="cv-verbs-expanded-master",
        title_ar="معجم الأفعال الإسبانية الموسع والشامل بالتصريفات الكاملة",
        entries=entries
    )
    return len(entries), seen

