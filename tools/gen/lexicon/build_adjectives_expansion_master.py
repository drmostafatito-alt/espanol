def build_adjectives_master(existing_norms: set[str]):
    entries = []
    seen = set()
    rank = 1

    for row in ADJECTIVES_MASTER:
        headword = row[0]
        norm = norm_vocab(headword)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        level = row[1]
        msa = row[2]
        eg = row[3]
        domain = row[4]

        ex_es = f"Esta persona es sumamente {headword} en su vida cotidiana."
        ex_ar = f"هذا الشخص {msa} للغاية في حياته اليومية."

        entry = make_adj(headword, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-adjectives-master.json",
        bundle_slug="cv-adjectives-master",
        title_ar="معجم الصفات الإسبانية الشامل والمتنوع للطباع والمشاعر والأشكال",
        entries=entries
    )
    return len(entries), seen

