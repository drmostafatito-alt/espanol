def build_nouns_arts_humanities(existing_norms: set[str]):
    entries = []
    seen = set()
    rank = 1

    for row in ARTS_ITEMS:
        headword = row[1]
        norm = norm_vocab(headword)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        gender = row[2]
        level = row[3]
        msa = row[4]
        eg = row[5]
        domain = row[6]

        art = "El" if gender == "m" else "La"
        ex_es = f"{art} {headword} enriquece la cultura y el pensamiento humano."
        ex_ar = f"الـ{msa} يثري الثقافة والفكر الإنساني."

        entry = make_noun(headword, gender, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-nouns-arts-humanities.json",
        bundle_slug="cv-nouns-arts-humanities",
        title_ar="معجم الفنون والآداب والموسيقى والعمارة والفلسفة",
        entries=entries
    )
    return len(entries), seen

