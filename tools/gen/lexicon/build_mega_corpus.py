def build_mega_corpus(existing_norms: set[str]):
    entries = []
    seen = set()
    rank = 1

    for row in VERBS_MASTER:
        lemma = row[0]
        norm = norm_vocab(lemma)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        paradigm = row[1]
        level = row[2]
        msa = row[3]
        eg = row[4]
        domain = row[5]

        ex_es = f"Solemos {lemma} con mucha frecuencia en estas circunstancias."
        ex_ar = f"نعتاد أن {msa} كثيراً في هذه الظروف."

        entry = make_verb(lemma, paradigm, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-verbs-master.json",
        bundle_slug="cv-verbs-master",
        title_ar="الأفعال الإسبانية الشاملة المصرفة: الحركة والفكر والتواصل والعمل",
        entries=entries
    )
    return len(entries), seen

