def build_thematic_travel(existing_norms: set[str]):
    entries = []
    seen = set()
    rank = 1

    for row in TRAVEL_ITEMS:
        kind = row[0]
        headword = row[1]
        param = row[2]
        level = row[3]
        msa = row[4]
        eg = row[5]
        domain = row[6]

        norm = norm_vocab(headword)
        if norm in existing_norms or norm in seen:
            continue
        seen.add(norm)

        if kind == "noun":
            gender = param if param in ("m", "f", "mf") else "m"
            art = "El" if gender == "m" else "La"
            ex_es = f"{art} {headword} es fundamental para organizar el viaje."
            ex_ar = f"الـ{msa} أساسي لتنظيم الرحلة."
            entry = make_noun(headword, gender, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        elif kind == "verb":
            paradigm = param or "ar"
            ex_es = f"Es conveniente {headword} antes de iniciar el trayecto."
            ex_ar = f"من المناسب أن {msa} قبل بدء الرحلة."
            entry = make_verb(headword, paradigm, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)
        else:
            ex_es = f"Viajamos {headword} durante nuestras vacaciones."
            ex_ar = f"نسافر {msa} أثناء عطلتنا."
            entry = make_adv(headword, level, msa, eg, ex_es, ex_ar, domain=domain, rank=rank)

        entries.append(entry)
        rank += 1

    emit_bundle(
        filename="vocab-cv-topic-travel.json",
        bundle_slug="cv-topic-travel",
        title_ar="معجم مفردات السفر والسياحة والمطارات والفنادق والمواصلات",
        entries=entries
    )
    return len(entries), seen

if __name__ == "__main__":
    count, _ = build_thematic_travel(get_existing_norms())
    print(f"Generated {count} entries in vocab-cv-topic-travel.json")
